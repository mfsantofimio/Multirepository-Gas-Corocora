-- =====================================================================
-- GAS COROCORA - Modelo de datos de negocio (H2)
-- Se ejecuta en cada arranque (spring.sql.init.mode=always). Es idempotente:
-- solo crea lo que no existe, nunca borra datos.
-- Las tablas de Camunda (ACT_*) las crea el motor; estas (GC_*) son del negocio
-- y se vinculan con las instancias por PROCESS_INSTANCE_ID.
-- =====================================================================

-- Usuario externo (suscriptor actual o potencial). Se registra en el portal
-- o se crea automaticamente al radicar una solicitud por Tasklist.
CREATE TABLE IF NOT EXISTS gc_suscriptor (
  documento        VARCHAR(20)  PRIMARY KEY,
  nombre           VARCHAR(120) NOT NULL,
  email            VARCHAR(120),
  telefono         VARCHAR(20),
  direccion        VARCHAR(200),
  municipio        VARCHAR(40),
  clave_hash       VARCHAR(64),            -- SHA-256(documento:clave); NULL = sin acceso al portal
  origen           VARCHAR(20)  DEFAULT 'PORTAL',
  fecha_registro   TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- Cuenta de servicio (contrato de gas de un predio). Nace en P3 (matricula).
CREATE TABLE IF NOT EXISTS gc_cuenta (
  numero_cuenta           VARCHAR(30)  PRIMARY KEY,
  documento               VARCHAR(20)  REFERENCES gc_suscriptor(documento),
  tipo_usuario            VARCHAR(20),
  estrato                 INT,
  direccion               VARCHAR(200),
  consumo_promedio_m3     DECIMAL(12,2),
  ultima_lectura          DECIMAL(12,2),
  estado                  VARCHAR(20)  DEFAULT 'ACTIVA',
  numero_solicitud_origen VARCHAR(30),
  fecha_alta              TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- P3 - Solicitud de conexion de un nuevo usuario
CREATE TABLE IF NOT EXISTS gc_solicitud_conexion (
  numero_solicitud     VARCHAR(30)   PRIMARY KEY,
  documento            VARCHAR(20)   NOT NULL REFERENCES gc_suscriptor(documento),
  process_instance_id  VARCHAR(64)   NOT NULL,
  direccion_predio     VARCHAR(200),
  municipio            VARCHAR(40),
  tipo_predio          VARCHAR(20),
  estrato              INT,
  distancia_red_metros DECIMAL(10,2),
  viabilidad           VARCHAR(30),
  valor_cotizacion     DECIMAL(14,2),
  numero_contrato      VARCHAR(30),
  numero_certificado   VARCHAR(30),
  numero_cuenta        VARCHAR(30),
  estado               VARCHAR(30),
  fecha_creacion       TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion  TIMESTAMP
);

-- P1 - Factura de un ciclo de facturacion
CREATE TABLE IF NOT EXISTS gc_factura (
  numero_factura          VARCHAR(30)   PRIMARY KEY,
  numero_cuenta           VARCHAR(30)   NOT NULL REFERENCES gc_cuenta(numero_cuenta),
  process_instance_id     VARCHAR(64)   NOT NULL,
  lectura_anterior        DECIMAL(12,2),
  lectura_actual          DECIMAL(12,2),
  consumo_m3              DECIMAL(12,2),
  porcentaje_ajuste       DECIMAL(6,2),
  total_pagar             DECIMAL(14,2),
  fecha_emision           DATE,
  fecha_limite_pago       DATE,
  referencia_pago         VARCHAR(30),   -- la asigna el servicio de Recaudo
  valor_pagado            DECIMAL(14,2),
  medio_pago              VARCHAR(30),
  fecha_pago              TIMESTAMP,
  numero_orden_suspension VARCHAR(30),
  estado                  VARCHAR(20),
  fecha_actualizacion     TIMESTAMP
);

-- P2 - Peticion, queja, reclamo o sugerencia
CREATE TABLE IF NOT EXISTS gc_pqrs (
  numero_radicado        VARCHAR(30)   PRIMARY KEY,
  numero_cuenta          VARCHAR(30)   NOT NULL REFERENCES gc_cuenta(numero_cuenta),
  process_instance_id    VARCHAR(64)   NOT NULL,
  tipo_solicitud         VARCHAR(20),
  canal                  VARCHAR(20),
  descripcion            VARCHAR(1000),
  valor_reclamado        DECIMAL(14,2),
  ruta_atencion          VARCHAR(30),
  respuesta              VARCHAR(2000),
  procede_ajuste         BOOLEAN,
  valor_ajuste           DECIMAL(14,2),
  numero_nota_credito    VARCHAR(30),
  motivo_recurso         VARCHAR(1000),
  decision_confirmada    BOOLEAN,
  estado                 VARCHAR(30),
  fecha_radicacion       DATE,
  fecha_limite_respuesta DATE,
  fecha_actualizacion    TIMESTAMP
);

-- Bitacora del caso: tareas creadas/completadas y actividades ejecutadas.
-- ROOT_PROCESS_INSTANCE_ID agrupa tambien los eventos de los subprocesos (call activity).
CREATE TABLE IF NOT EXISTS gc_evento_caso (
  id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  root_process_instance_id VARCHAR(64)  NOT NULL,
  process_instance_id      VARCHAR(64)  NOT NULL,
  proceso                  VARCHAR(60),
  referencia               VARCHAR(40),
  evento                   VARCHAR(30)  NOT NULL,
  actividad                VARCHAR(150),
  usuario                  VARCHAR(60),
  detalle                  VARCHAR(500),
  fecha                    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_cuenta_documento    ON gc_cuenta(documento);
CREATE INDEX IF NOT EXISTS idx_solicitud_documento ON gc_solicitud_conexion(documento);
CREATE INDEX IF NOT EXISTS idx_solicitud_pi        ON gc_solicitud_conexion(process_instance_id);
CREATE INDEX IF NOT EXISTS idx_factura_cuenta      ON gc_factura(numero_cuenta);
CREATE INDEX IF NOT EXISTS idx_factura_pi          ON gc_factura(process_instance_id);
CREATE INDEX IF NOT EXISTS idx_pqrs_cuenta         ON gc_pqrs(numero_cuenta);
CREATE INDEX IF NOT EXISTS idx_pqrs_pi             ON gc_pqrs(process_instance_id);
CREATE INDEX IF NOT EXISTS idx_evento_root         ON gc_evento_caso(root_process_instance_id);
